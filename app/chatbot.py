def get_chatbot_response(
    message: str,
    conversation_history: Optional[list] = None,
    job_context: Optional[str] = None,
    role: str = "PUBLIC",
    jobs: Optional[list] = None,
) -> str:
    """
    Generate a response for a candidate.

    message:              current user message
    conversation_history: optional [{"role": "user"|"assistant", "content": "..."}]
    job_context:          optional current job listings from the backend (text lines or JSON)
    jobs:                 optional structured job list from the backend (preferred)
    role:                 role from the Java backend (PUBLIC / CANDIDATE = candidate)
    """

    if not message or not message.strip():
        raise ValueError("Message cannot be empty.")

    message = message.strip()

    # 1. Candidates only
    if _normalize_role(role) not in CANDIDATE_ROLES:
        return STAFF_ROLE_MESSAGE

    # 2. No questions about internal roles, no secrets
    if is_restricted_topic(message):
        return RESTRICTED_TOPIC_MESSAGE
    if is_secrets_request(message):
        return SECRETS_MESSAGE

    parsed_jobs = parse_jobs(job_context, jobs)

    # 3. Small talk: hi / hlo / ok / okay / thanks / bye / how are you / help ...
    intent = detect_small_talk(message)
    if intent:
        return small_talk_reply(intent, _last_bot_message(conversation_history), bool(parsed_jobs))

    # "hi, show me python jobs" / "ok what about salary" -> answer the real question
    prefix_intent = None
    # "help me with python jobs", "can you help me find jobs in pune" -> drop the request wrapper
    message = re.sub(r"^\s*(please |pls |kindly )?((can|could|will|would) you (please )?)?"
                     r"(help me|assist me|i need help|i want help|need help)( to| with| in| for)?"
                     r"( find(ing)?| get(ting)?| search(ing)?| look(ing)? for| know| understand)?\s+",
                     "", message, flags=re.I) or message
    for _ in range(2):                      # "ok thank you, show jobs" -> "show jobs"
        p_intent, message = split_leading_small_talk(message)
        prefix_intent = prefix_intent or p_intent
    if prefix_intent and detect_small_talk(message):
        # "hello, how are you" / "thanks, bye" -> answer the more specific part
        return small_talk_reply(detect_small_talk(message), _last_bot_message(conversation_history),
                                bool(parsed_jobs))

    # 4. Menu number from the help list ("1", "2)", "option 3")
    menu = re.fullmatch(r"(?:option\s*)?([1-4])\s*[).]?", message, re.I)
    if menu:
        choice = menu.group(1)
        if choice == "1":
            return _jobs_answer("show all jobs", job_context, jobs) if parsed_jobs \
                else NO_JOBS_MESSAGE
        if choice == "2":
            return PLATFORM_ACTIONS[0][1] + "\n\n" + PLATFORM_ACTIONS[1][1]
        if choice == "3":
            return PLATFORM_ACTIONS[2][1]
        return CAREER_HELP_MESSAGE

    # 5. Candidate platform actions ("how do I apply for the python job?" -> apply steps)
    for pattern, reply in PLATFORM_ACTIONS:
        if pattern.search(message):
            return reply

    bundle = _get_model()
    model = bundle["model"]
    min_conf = bundle["min_topic_confidence"]

    # 6. "list career roles"
    if ROLE_LIST_RULE.search(message) and not EXPLICIT_JOB_WORDS.search(
            re.sub(r"\bjob roles?\b", "", message, flags=re.I)):
        return _format_role_list(model)

    # 7. Career intent wins over job search when a career role AND a career topic are named
    #    and no job filter is used ("skills for data analyst" is not a job search).
    all_roles = _detect_all_roles(model, message)
    job_role, role_name = model.detect_role(message)
    rule_topics = _rule_topics(message, role_name)
    explicit_job = bool(EXPLICIT_JOB_WORDS.search(message))

    # 7a. Comparison: "data analyst vs data scientist"
    if len(all_roles) >= 2 and COMPARE_RULE.search(message) and not explicit_job:
        return _format_compare(model, all_roles, [t for t in rule_topics if t != "roadmap"])

    career_first = bool(job_role and rule_topics and not explicit_job)

    # 7b. "data scientist", "tell me about web developer", "what is a qa engineer", "tester"
    #     -> career overview, unless we have an opening with that exact title (then job details)
    overview_first = bool(job_role and not rule_topics and not explicit_job
                          and _is_overview_request(message, role_name)
                          and not re.match(r"^\s*(and|what about|how about|same for|for)\b", message, re.I))
    if overview_first and not _exact_title_job(message, role_name, parsed_jobs):
        return _overview_reply(model, job_role, parsed_jobs)

    previous_msgs = _previous_user_messages(conversation_history)
    last_user = previous_msgs[0] if previous_msgs else None

    # 7c. Career follow-up with only a new role: "how to become a data analyst" -> "and for a data scientist?"
    followup_topics = []
    if job_role and not rule_topics and not explicit_job and last_user \
            and re.match(r"^\s*(and|what about|how about|same for|for|also)\b", message, re.I) \
            and not (parsed_jobs and is_job_search(last_user, parsed_jobs)):
        _, prev_name = model.detect_role(last_user)
        followup_topics, _ = _resolve_topics(model, last_user, prev_name, min_conf)
        if followup_topics:
            career_first = True

    # 8. Job search from backend data only: experience, skills, city, job type, title, details
    if parsed_jobs and not career_first:
        if is_job_search(message, parsed_jobs, last_user):
            reply = _jobs_answer(message, job_context, jobs, last_user)
            # "about data analyst" -> job details + offer career guidance for that role
            if job_role and _related_jobs(job_role, parsed_jobs) and not explicit_job:
                r = _display_role(job_role).lower()
                reply += (f"\n\n\U0001F4A1 Want career guidance too? Ask \"how to become a {r}\", "
                          f"\"skills needed for a {r}\" or \"salary of a {r}\".")
            if re.search(r"\bjob roles?\b", message, re.I):
                reply += ("\n\n\U0001F4A1 Looking for career guidance instead? Say \"list career roles\" "
                          f"to see the {len(model.roles)} roles I can explain.")
            return reply
    elif not parsed_jobs and JOB_LISTING.search(message) and not career_first:
        return NO_JOBS_MESSAGE

    # 9. Career questions
    if overview_first:
        return _overview_reply(model, job_role, parsed_jobs)

    topics, confidence = _resolve_topics(model, message, role_name, min_conf)
    if followup_topics and not _rule_topics(message, role_name):
        topics = followup_topics

    previous = [m for m in previous_msgs if not is_restricted_topic(m)][:4]

    # Follow-up without a role ("what about the salary?") -> role from earlier messages
    if job_role is None and topics:
        for prev in previous:
            job_role, _ = model.detect_role(prev)
            if job_role:
                break

    # Follow-up with only a role ("and for a data analyst?") -> topic from earlier message
    if not topics and job_role and previous:
        prev_role, prev_name = model.detect_role(previous[0])
        prev_topics, _ = _resolve_topics(model, previous[0], prev_name, min_conf)
        topics = prev_topics

    if not topics and job_role:
        return _overview_reply(model, job_role, parsed_jobs)

    if not topics:
        _log_unknown(message, confidence)
        if prefix_intent:
            # "thank you for <something I don't understand>" -> still a thank-you
            return small_talk_reply(prefix_intent, _last_bot_message(conversation_history),
                                    bool(parsed_jobs))
        if parsed_jobs and len(message.split()) <= 3:
            return (f"I couldn't find any current openings or career roles matching \"{message}\". "
                    "Try a skill, city or job title (e.g. \"python jobs\", \"jobs in Hyderabad\"), "
                    "say \"show all jobs\", or \"list career roles\" for career guidance.")
        return FALLBACK_MESSAGE

    if job_role is None:
        _log_unknown(message, confidence)
        label = "a step-by-step roadmap" if topics == ["roadmap"] else \
            " and ".join(TOPIC_LABELS.get(t, t) for t in topics)
        return ("Which job role are you asking about? I can tell you about "
                f"{label} for {len(model.roles)} roles, for example "
                f"{_role_examples(model)}.\n\nSay \"list career roles\" to see them all.")

    note = _openings_note(job_role, parsed_jobs)

    if topics == ["roadmap"]:
        return _format_roadmap(model, job_role) + note + _suggestions(
            job_role, ["roadmap", "skills", "tools_technologies", "career_growth", "education"])

    if len(topics) > 1:
        return _format_multi(model, job_role, topics, message) + note + _suggestions(job_role, topics)

    topic = topics[0]
    dataset_question, dataset_answer = model.answer(job_role, topic, message)
    answer = dataset_answer
    generated = _generate(dataset_question, job_role)
    if generated and _similar(generated, dataset_answer) >= MIN_ANSWER_SIMILARITY:
        answer = generated

    return _format_single(job_role, topic, answer) + note + _suggestions(job_role, [topic])


def get_chatbot_debug(message: str, role: str = "PUBLIC") -> dict:
    """Testing helper: detected job role, topic and confidence."""
    bundle = _get_model()
    model = bundle["model"]
    job_role, name = model.detect_role(message)
    topic, conf = model.predict_topic(message, name)
    topics, _ = _resolve_topics(model, message, name, bundle["min_topic_confidence"])
    return {"job_role": job_role, "topic": topic, "confidence": round(conf, 3),
            "resolved_topics": topics,
            "all_roles": _detect_all_roles(model, message),
            "small_talk": detect_small_talk(message),
            "restricted": is_restricted_topic(message),
            "candidate_role": _normalize_role(role) in CANDIDATE_ROLES}
