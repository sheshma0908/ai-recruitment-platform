_bundle = None
_generator = None
_generator_unavailable = False
_lock = threading.Lock()


def _get_model() -> dict:
    global _bundle
    if _bundle is None:
        with _lock:
            if _bundle is None:
                if not MODEL_PATH.exists():
                    raise RuntimeError(
                        f"Chatbot model not found at {MODEL_PATH}. Run 'python training/chatbot/train_chatbot.py' first.")
                _bundle = joblib.load(MODEL_PATH)
    return _bundle


def _get_generator():
    global _generator, _generator_unavailable
    if CHATBOT_MODE in ("dataset", "retrieval") or _generator_unavailable:
        return None
    if _generator is None:
        with _lock:
            if _generator is None and not _generator_unavailable:
                if not (GENERATIVE_MODEL_DIR / "config.json").exists():
                    _generator_unavailable = True
                    return None
                try:
                    import torch
                    from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
                    device = "cuda" if torch.cuda.is_available() else "cpu"
                    tok = AutoTokenizer.from_pretrained(GENERATIVE_MODEL_DIR)
                    mdl = AutoModelForSeq2SeqLM.from_pretrained(GENERATIVE_MODEL_DIR).to(device).eval()
                    _generator = (tok, mdl, device)
                except Exception:
                    _generator_unavailable = True
                    return None
    return _generator


def load_chatbot_model() -> None:
    """Load the model now (called from app/main.py at server startup)."""
    _get_model()


def reload_models() -> None:
    """Call after retraining to load the new models without a restart."""
    global _bundle, _generator, _generator_unavailable
    with _lock:
        _bundle, _generator, _generator_unavailable = None, None, False


