def _generate(question: str, role: str) -> Optional[str]:
    gen = _get_generator()
    if gen is None:
        return None
    import torch
    tok, mdl, device = gen
    prompt = f"Answer this career question. job role: {role} | question: {question.strip()}"
    enc = tok(prompt, max_length=96, truncation=True, return_tensors="pt").to(device)
    with torch.no_grad():
        out = mdl.generate(**enc, max_new_tokens=200, num_beams=3, no_repeat_ngram_size=4)
    text = tok.decode(out[0], skip_special_tokens=True).strip()
    return text if len(text) >= 20 else None


def _similar(a: str, b: str) -> float:
    return SequenceMatcher(None, normalize_text(a).split(), normalize_text(b).split()).ratio()


def _log_unknown(message: str, score: float) -> None:
    if not UNKNOWN_LOG_PATH:
        return
    try:
        with open(UNKNOWN_LOG_PATH, "a", encoding="utf-8") as f:
            f.write(json.dumps({"time": datetime.now().isoformat(timespec="seconds"),
                                "message": message, "best_score": round(score, 3)}) + "\n")
    except OSError:
        pass


# ---------------- career helpers ----------------

def _display_role(role: str) -> str:
    """'Product Manager (Entry-level)' -> 'Product Manager'."""
    return base_role_name(role)


def _detect_all_roles(model, text: str) -> List[str]:
    """Every dataset role named in the text, in order of appearance (no overlaps)."""
    q = f" {normalize_text(text)} "
    taken = [False] * len(q)
    found = []
    for name, role in model.role_lookup:          # longest names first
        for m in re.finditer(rf"(?<= ){re.escape(name)}(?= )", q):
            if any(taken[m.start():m.end()]):
                continue
            for i in range(m.start(), m.end()):
                taken[i] = True
            found.append((m.start(), role))
    seen, roles = set(), []
    for _, role in sorted(found):
        if role not in seen:
            seen.add(role)
            roles.append(role)
    return roles


def _strip_role(text: str, role_name: Optional[str]) -> str:
    q = normalize_text(text)
    if role_name:
        q = re.sub(rf"\b{re.escape(role_name)}\b", " ", q)
    return re.sub(r"\s+", " ", q).strip()


def _rule_topics(text: str, role_name: Optional[str] = None) -> List[str]:
    """Topics named by keyword rules, in the order they appear. [] = no rule matched."""
    q = _strip_role(text, role_name)
    if ROADMAP_RULE.search(q) and not re.search(
            r"\b(skills?|study|studies|degree|course|courses|qualifications?|certifications?|"
            r"salary|tools?)\b", q):
        return ["roadmap"]
    hits = []
    for topic, rx in TOPIC_RULES:
        m = rx.search(q)
        if m:
            hits.append((m.start(), topic))
    topics = [t for _, t in sorted(hits)]
    # "what does a X do every day" -> daily tasks, not responsibilities
    if "daily_tasks" in topics and "responsibilities" in topics:
        topics.remove("responsibilities")
    # "what does a X do" is responsibilities even if another word matched by accident
    if not topics and re.search(r"\bwhat (does|do|will)\b.*\bdo\b", q):
        topics = ["responsibilities"]
    return topics


def _is_overview_request(text: str, role_name: Optional[str]) -> bool:
    """'tell me about data analyst', 'what is a data analyst', or just 'data analyst'."""
    rest = _strip_role(text, role_name)
    rest = re.sub(r"\b(a|an|the|role|job|career|position|profile|field|please|pls|me|of|as)\b", " ", rest)
    rest = re.sub(r"\s+", " ", rest).strip()
    return not rest or bool(OVERVIEW_RULE.search(rest)) and len(rest.split()) <= 5


def _answer_for(model, role: str, topic: str, message: str = "") -> str:
    _, ans = model.answer(role, topic, message)
    return (ans or "").strip()


def _related_jobs(role: str, parsed_jobs) -> list:
    """Current openings whose title matches the career role (e.g. 'data analyst')."""
    if not parsed_jobs:
        return []
    name = re.sub(r"\s*\([^)]*\)", "", _display_role(role))
    stems = [w[:5] for w in normalize_text(name).split()]
    out = []
    for j in parsed_jobs:
        title_stems = {w[:5] for w in normalize_text(j.title).split()}
        if stems and all(s in title_stems for s in stems):     # "data scientist" ~ "data science"
            out.append(j)
    return out


def _exact_title_job(message: str, role_name: Optional[str], parsed_jobs) -> bool:
    """True if a current opening's title is exactly the role named ('data analyst' job)."""
    if not role_name or not parsed_jobs:
        return False
    rn = normalize_text(role_name).rstrip("s")
    return any(normalize_text(j.title).rstrip("s") == rn for j in parsed_jobs)


def _openings_note(role: str, parsed_jobs) -> str:
    related = _related_jobs(role, parsed_jobs)
    if not related:
        return ""
    if len(related) == 1:
        j = related[0]
        where = f" ({j.location})" if j.location else ""
        return (f"\n\n\U0001F4CC We have a current opening for **{j.title}**{where}. "
                f"Say \"details of {j.title}\" to see it.")
    return (f"\n\n\U0001F4CC We have {len(related)} current openings for this role. "
            f"Say \"{_display_role(role).lower()} jobs\" to see them.")


def _overview_reply(model, role: str, parsed_jobs) -> str:
    note = _openings_note(role, parsed_jobs)
    if not note and parsed_jobs:
        note = (f"\n\nThere's no {_display_role(role)} opening right now. "
                "Say \"show all jobs\" to see current openings.")
    return (_format_overview(model, role) + note
            + _suggestions(role, ["responsibilities", "skills", "salary", "career_growth"]))


def _suggestions(role: str, used: List[str], n: int = 3) -> str:
    r = _display_role(role).lower()
    picks = [SUGGEST_TEXT[t].format(r=r) for t in SUGGEST_ORDER if t not in used][:n]
    return "\n\n\U0001F4A1 You can also ask: " + " • ".join(f"\"{p}\"" for p in picks)


SALARY_NOTE = ("\n_Note: these figures are general (mostly US-market) estimates from the career "
               "dataset. Salaries in India vary by city, company and experience._")


def _format_single(role: str, topic: str, answer: str) -> str:
    text = f"**{_display_role(role)} — {TOPIC_TITLES.get(topic, topic)}**\n{answer}"
    return text + (SALARY_NOTE if topic == "salary" else "")


def _format_multi(model, role: str, topics: List[str], message: str) -> str:
    lines = [f"**{_display_role(role)}**"]
    for t in topics:
        lines.append(f"\n**{TOPIC_TITLES.get(t, t)}:** {_answer_for(model, role, t, message)}")
    return "\n".join(lines) + (SALARY_NOTE if "salary" in topics else "")


def _format_roadmap(model, role: str) -> str:
    name = _display_role(role)
    steps = [
        ("Get the right education", "education"),
        ("Build the core skills", "skills"),
        ("Learn the tools", "tools_technologies"),
        ("Get your first role", "getting_started"),
        ("Grow your career", "career_growth"),
    ]
    out = [f"**How to become a {name} — step-by-step roadmap**"]
    for i, (title, topic) in enumerate(steps, 1):
        out.append(f"\n**{i}. {title}**\n{_answer_for(model, role, topic)}")
    out.append("\n✅ Tip: build 2-3 practical projects for your portfolio and tailor your "
               "resume to the skills above before applying.")
    return "\n".join(out)


def _format_overview(model, role: str) -> str:
    name = _display_role(role)
    parts = [("What they do", "responsibilities"), ("Key skills", "skills"),
             ("Salary", "salary"), ("Career growth", "career_growth")]
    out = [f"**{name} — role overview**"]
    for title, topic in parts:
        out.append(f"\n**{title}:** {_answer_for(model, role, topic)}")
    return "\n".join(out) + SALARY_NOTE


def _format_compare(model, roles: List[str], topics: List[str]) -> str:
    roles = roles[:3]
    if not topics or topics == ["roadmap"]:
        topics = ["responsibilities", "skills", "salary", "career_growth"]
    title = " vs ".join(_display_role(r) for r in roles)
    out = [f"**{title}**"]
    for t in topics:
        out.append(f"\n**{TOPIC_TITLES.get(t, t)}**")
        for r in roles:
            out.append(f"- **{_display_role(r)}:** {_answer_for(model, r, t)}")
    out.append("\n\U0001F4A1 Pick the one whose daily work and skills excite you most. "
               "Ask \"how to become a " + _display_role(roles[0]).lower() + "\" for a roadmap.")
    return "\n".join(out) + (SALARY_NOTE if "salary" in topics else "")


def _format_role_list(model) -> str:
    names = sorted({_display_role(r) for r in model.roles})
    return (f"I can give career guidance on these {len(names)} job roles:\n"
            + ", ".join(names)
            + "\n\nAsk e.g. \"how to become a data analyst\" or \"salary of a web developer\".")


def _resolve_topics(model, text: str, role_name: Optional[str], min_conf: float) -> Tuple[List[str], float]:
    """Topics for a message: keyword rules first, then the ML classifier."""
    topics = _rule_topics(text, role_name)
    if topics:
        return topics, 1.0
    topic, conf = model.predict_topic(text, role_name)
    if conf >= min_conf:
        if topic == "getting_started":
            return ["roadmap"], conf
        return [topic], conf
    return [], conf


