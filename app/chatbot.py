"""
Module -- Candidate Chatbot  (v3.0 "smart conversation")

Called by the POST /chat endpoint in app/main.py. No Groq / OpenAI / external LLM.
Model: app/models/candidate_chatbot.joblib, trained by training/chatbot/train_chatbot.py.

* Only for candidates. Logged-in staff roles (HR, RECRUITER, HIRING_MANAGER,
  EMPLOYEE, INTERVIEWER, SUPER_ADMIN) get a "candidates only" message.
* Questions about recruiters, HR, hiring managers, super admins, interviewers
  or employees are not answered.
* Small talk (app/chatbot_smalltalk.py): hi / hlo / hey, ok / okay / k, thanks,
  bye, how are you, who are you, help, yes / no, praise, complaints - with typo
  tolerance ("hiii", "okkk", "thnks"). Replies are context-aware (e.g. "ok" after
  a job list suggests asking for job details). "hi, show me python jobs" ->
  the greeting is dropped and the question is answered.
* Career questions are answered from the Career Guidance QA Dataset:
    - high-precision keyword rules pick the topic first ("how to become" ->
      roadmap, "skills" -> skills, "salary" -> salary ...); the trained TF-IDF +
      Logistic Regression topic classifier is used when no rule applies.
    - "how to become a data analyst" / "steps" / "process" / "roadmap"
      -> a step-by-step roadmap (education, skills, tools, getting started, growth)
    - "tell me about data analyst" / "what is a data analyst" / just the role
      -> a role overview (what they do, skills, salary, growth)
    - "skills and salary of a data analyst" -> both topics in one answer
    - "data analyst vs data scientist" -> side-by-side comparison
    - "list career roles" -> every role the bot can talk about
    - follow-ups reuse the role / topic from earlier messages
    - every answer ends with suggested follow-up questions, and links to a
      current opening for that role when there is one
* Optional: if app/models/flan_t5_candidate/ exists (train_generative.py), single-topic
  answers are generated by the fine-tuned flan-t5-small, checked against the dataset answer.
* Job search (app/job_search.py) - by experience ("2-3 years", "fresher"), skill
  ("python"), city ("Hyderabad"), job type ("internship"), title, or any mix of these,
  plus full details of one job. Answers come only from the jobs the backend sends
  (job_context text/JSON or the structured `jobs` list). Runs before the career model.
"""

